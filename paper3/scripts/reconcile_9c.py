"""Every Phase-9C number, as originally scored beside its corrected value.

The pre-registered scores were computed from a PostToolUse hook that never saw
a failed tool call. The canonical dataset (build_9c_canonical.py) restores
those calls from the subagent transcripts. This script runs the SAME frozen
code -- `heart_instrument.convert.convert`, `phase_c_analyze.replay`, and the
JSON outputs of the frozen analyses run under each source -- on both datasets
and prints them side by side, so no corrected number can be read without its
original, and no label can quietly change.

Convention, as for H17b: the pre-registered score is recorded as originally
scored, the corrected value beside it, and the label is re-derived from the
pre-registered clause applied to the corrected value.

Run from repo root, after the analyses have run under both sources:
    python scripts/reconcile_9c.py
"""
from __future__ import annotations

import json
import statistics
import subprocess
import sys
from pathlib import Path
from typing import Dict, List

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from phase_c_analyze import replay                                # noqa: E402
from c2_source import HOOK_DIR, CANON_DIR                         # noqa: E402

OUT = ROOT / "data" / "swebench_pilot" / "RECONCILIATION_9C.md"
SHELL = {"Bash", "PowerShell"}
MODELS = ("opus", "fable")


def sha() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True,
                              text=True, check=True).stdout.strip()[:12]
    except Exception:
        return "(unknown)"


def load(d: Path) -> Dict:
    runs = {}
    for p in sorted(d.glob("S*_*_r1.json")):
        r = json.loads(p.read_text(encoding="utf-8"))
        if r["model"] not in MODELS:
            continue
        recs = [json.loads(l) for l in (d / r["spec"] / f"session_{r['model']}_r1.jsonl")
                .read_text(encoding="utf-8").splitlines() if l.strip()]
        rp = replay(d / r["spec"] / f"replay_{r['model']}_r1" / "trajectory.json",
                    r["dt_seconds"])
        runs[(r["spec"], r["model"])] = {
            "n": r["n_actions"], "dts": r["dt_seconds"],
            "median_dt": r["dt_stats"]["median"],
            "E_X": sum(1 for x in recs if x["tool_name"] in SHELL and x["error_indicator"]),
            "reads": r["tools_used"].get("Read", 0),
            "max_frust": rp["max_frust"], "reached": rp["reached"],
            "clamped": rp["clamped"], "a6": rp.get("a6_fires", rp.get("a6")),
        }
    return runs


def fmt(a, b, nd=3):
    if isinstance(a, float) or isinstance(b, float):
        same = abs(float(a) - float(b)) < 10 ** -nd
        s = f"{a:.{nd}f} → {b:.{nd}f}"
    else:
        same = a == b
        s = f"{a} → {b}"
    return s if same else f"**{s}**"


def main() -> int:
    H = load(HOOK_DIR)
    C = load(CANON_DIR)
    specs = sorted({s for s, _ in H})
    ah = json.loads((HOOK_DIR / "_analysis.json").read_text(encoding="utf-8"))
    ac = json.loads((CANON_DIR / "_analysis.json").read_text(encoding="utf-8"))
    bh = json.loads((HOOK_DIR / "_budget_ceiling.json").read_text(encoding="utf-8"))
    bc = json.loads((CANON_DIR / "_budget_ceiling.json").read_text(encoding="utf-8"))
    kh = json.loads((HOOK_DIR / "_bracketing.json").read_text(encoding="utf-8"))
    kc = json.loads((CANON_DIR / "_bracketing.json").read_text(encoding="utf-8"))

    O: List[str] = []
    w = O.append
    w("# Phase 9C — reconciliation: as originally scored → corrected")
    w("")
    w(f"Generated by `scripts/reconcile_9c.py` at `{sha()}`. Left of each arrow: "
      "the published value, computed from the PostToolUse hook, which never saw "
      "a failed tool call. Right: the same frozen code on the canonical "
      "transcript-derived dataset (`build_9c_canonical.py`). **Bold** marks a "
      "value that moved. Calls that both instruments logged carry identical "
      "content in both datasets (the canonical records add only a `source` "
      "field marking provenance), so every change traces to the 6 restored failed calls "
      "— all in the Fable 5.1 arm, all among each session's first two actions.")
    w("")

    # ---- pre-registered hypotheses ----
    def pos_dir(R):
        return sum(1 for s in specs if R[(s, "opus")]["median_dt"] > R[(s, "fable")]["median_dt"])
    h16h, h16c = ah["h16"], ac["h16"]
    w("## Pre-registered hypotheses")
    w("")
    w("| | clause | as originally scored | corrected | label |")
    w("|---|---|---|---|---|")
    w(f"| **H16** cadence direction | Fable median Δt below Opus, per spec, exact Wilcoxon | "
      f"{pos_dir(H)}/8 in direction, p = {h16h['p']:.4f}, median diff {h16h['median_diff']:+.3f} s | "
      f"**{pos_dir(C)}/8, p = {h16c['p']:.4f}, median diff {h16c['median_diff']:+.3f} s** | "
      f"INCONCLUSIVE → {'INCONCLUSIVE' if h16c['p'] >= 0.05 else '**CHANGED**'} |")
    w(f"| **H17a** Read-burst counts | Fable more Reads, exact Wilcoxon | "
      f"p = {ah['h17a']['p']:.4f} | p = {ac['h17a']['p']:.4f} | "
      f"INCONCLUSIVE → {'INCONCLUSIVE' if ac['h17a']['p'] >= 0.05 else '**CHANGED**'} |")
    w(f"| **H17b** Read → frustration | partial ρ given action count; falsified if not distinguishable from 0 | "
      f"partial {ah['h17b']['partial']:.3f}, p = {ah['h17b']['p']:.4f} | "
      f"partial {ac['h17b']['partial']:.3f}, p = {ac['h17b']['p']:.4f} | "
      f"FALSIFIED under clause, canonical *did not replicate* → "
      f"{'unchanged' if ac['h17b']['p'] >= 0.05 else '**CHANGED**'} |")
    w(f"| **H18** clamp rate | ≤ 20% per arm | Opus {ah['clamps']['opus']}/8, Fable {ah['clamps']['fable']}/8 | "
      f"Opus {ac['clamps']['opus']}/8, Fable {ac['clamps']['fable']}/8 | "
      f"SUPPORTED (zero-clamp branch) → "
      f"{'unchanged' if sum(ac['clamps'].values()) == 0 else '**CHANGED**'} |")
    w("")

    # ---- what moves inside the canonical wording ----
    pooled = {src: {m: statistics.median([d for s in specs for d in R[(s, m)]["dts"]])
                    for m in MODELS} for src, R in (("hook", H), ("canon", C))}
    mx = {src: {m: max(R[(s, m)]["max_frust"] for s in specs) for m in MODELS}
          for src, R in (("hook", H), ("canon", C))}
    reads = {src: (min(R[k]["reads"] for k in R), max(R[k]["reads"] for k in R))
             for src, R in (("hook", H), ("canon", C))}
    w("## Numbers inside the canonical withdrawal and erratum wording")
    w("")
    w("| where | quantity | as originally scored | corrected |")
    w("|---|---|---|---|")
    w(f"| W1 | Read calls per session (both arms) | {reads['hook'][0]}–{reads['hook'][1]} | {reads['canon'][0]}–{reads['canon'][1]} |")
    w(f"| W1 | H17b partial ρ, permutation p | {ah['h17b']['partial']:.2f}, {ah['h17b']['p']:.3f} | "
      f"{fmt(round(ah['h17b']['partial'], 2), round(ac['h17b']['partial'], 2), 2)}, {fmt(round(ah['h17b']['p'], 3), round(ac['h17b']['p'], 3), 3)} |")
    w(f"| W2 | maximum modelled frustration, Opus 5 / Fable 5.1 | "
      f"{mx['hook']['opus']:.3f} / {mx['hook']['fable']:.3f} | "
      f"{fmt(mx['hook']['opus'], mx['canon']['opus'])} / {fmt(mx['hook']['fable'], mx['canon']['fable'])} |")
    w(f"| W2 | sessions reaching the clamp | {sum(ah['clamps'].values())}/16 | {sum(ac['clamps'].values())}/16 |")
    w(f"| W3 | tasks in predicted direction, p, median difference | "
      f"{pos_dir(H)}/8, {h16h['p']:.2f}, {h16h['median_diff']:+.2f} s | "
      f"**{pos_dir(C)}/8, {h16c['p']:.2f}, {h16c['median_diff']:+.2f} s** |")
    w(f"| E2c | pooled median Δt, Opus 5 / Fable 5.1 | "
      f"{pooled['hook']['opus']:.2f} / {pooled['hook']['fable']:.2f} s | "
      f"{fmt(pooled['hook']['opus'], pooled['canon']['opus'], 2)} / {fmt(pooled['hook']['fable'], pooled['canon']['fable'], 2)} s |")
    w("")

    # ---- floor, ceiling, bracketing ----
    def feas(rows, key="E_X"):
        return sum(1 for r in rows if r[key] >= 5)
    w("## Evidence floor and budget ceiling")
    w("")
    w("| quantity | as originally scored | corrected |")
    w("|---|---|---|")
    w(f"| sessions with E_X ≥ 5 (can fire at full budget) | {feas(bh['rows'])}/16 | {feas(bc['rows'])}/16 |")
    w(f"| median E_X | {statistics.median(r['E_X'] for r in bh['rows']):.1f} | "
      f"{fmt(statistics.median(r['E_X'] for r in bh['rows']), statistics.median(r['E_X'] for r in bc['rows']), 1)} |")
    for r_ in ("1", "2", "4"):
        w(f"| I2 CUSUM fire rate at r = {r_} | {bh['direct'][r_]['i2']:.1%} | "
          f"{fmt(round(bh['direct'][r_]['i2'] * 100, 1), round(bc['direct'][r_]['i2'] * 100, 1), 1)}% |")
        w(f"| I1 no-decay fire rate at r = {r_} | {bh['direct'][r_]['nd']:.1%} | "
          f"{fmt(round(bh['direct'][r_]['nd'] * 100, 1), round(bc['direct'][r_]['nd'] * 100, 1), 1)}% |")
    w("")
    w("Exact values over 16 sessions. Rounded to whole percent elsewhere, 12.5% "
      "becomes 12% under Python's round-half-to-even while 37.5% becomes 38%; "
      "quote one decimal when printing these.")
    w("")
    w("### Qualitative labels, not just numbers")
    w("")
    w("A number can move without a label changing, and a label can change "
      "while every hypothesis verdict stands. The bracketing claim — most "
      "legacy sessions can fire, most 9C sessions cannot — is checked here per "
      "definition, because an earlier version of this reconciliation reported "
      "the 7 → 10/16 move below without noticing that it flips this label.")
    w("")
    w("| definition | legacy feasible | 9C feasible, original → corrected | direction holds, original → corrected |")
    w("|---|---|---|---|")
    leg = {x["id"]: x for x in kh["legacy"]}
    for x in kh.get("legacy_exec", []):
        leg[x["id"]].update(x)
    for label, lkey, ckey, src in (("execution-only (primary)", "E_X", "E_XH", "c9_exec"),
                                    ("frozen observer's input", "E", "E_O", "c9"),
                                    ("hook, content-inflated", "E", "E_H", "c9")):
        lf = sum(1 for x in leg.values() if x.get(lkey, 0) >= 5)
        a = sum(1 for x in kh[src] if x.get(ckey, 0) >= 5)
        b = sum(1 for x in kc[src] if x.get(ckey, 0) >= 5)
        ha, hb = lf / 20 > 0.5 > a / 16, lf / 20 > 0.5 > b / 16
        w(f"| {label} | {lf}/20 | {fmt(a, b)}/16 | "
          f"{'holds' if ha else 'fails'} → {'holds' if hb else '**FAILS**'} |")
    w("")
    w("**The direction claim no longer holds under every definition.** It holds "
      "under the primary definition and fails under the content-inflated one, "
      "where a majority of 9C sessions now clear the floor. Every statement "
      "that it \"holds in direction under every definition\" must be scoped.")
    w("")
    w("### 9C feasibility under every evidence definition (bracketing)")
    w("")
    defs = [("execution-only (primary)", "E_XH"), ("frozen observer's input", "E_O"),
            ("hook, content-inflated", "E_H")]
    w("| definition | as originally scored | corrected |")
    w("|---|---|---|")
    for label, key in defs:
        def cnt(k):
            src = k.get("c9_exec") if key == "E_XH" else k.get("c9")
            return sum(1 for x in src if x.get(key, 0) >= 5) if src else None
        w(f"| {label} | {cnt(kh)}/16 | {fmt(cnt(kh), cnt(kc))}/16 |")
    w("")

    # ---- per run ----
    w("## Per run")
    w("")
    w("| run | n | median Δt (s) | E_X | Reads | peak frustration | reached 0.7 | clamp |")
    w("|---|---|---|---|---|---|---|---|")
    for s in specs:
        for m in MODELS:
            h, c = H[(s, m)], C[(s, m)]
            w(f"| {s} {m} | {fmt(h['n'], c['n'])} | {fmt(h['median_dt'], c['median_dt'])} | "
              f"{fmt(h['E_X'], c['E_X'])} | {fmt(h['reads'], c['reads'])} | "
              f"{fmt(h['max_frust'], c['max_frust'])} | {fmt(h['reached'], c['reached'])} | "
              f"{fmt(h['clamped'], c['clamped'])} |")
    w("")

    OUT.write_text("\n".join(O), encoding="utf-8")
    snap = {"h16": {"hook": h16h, "canon": h16c, "dir_hook": pos_dir(H), "dir_canon": pos_dir(C)},
            "h17a": {"hook": ah["h17a"], "canon": ac["h17a"]},
            "h17b": {"hook": ah["h17b"], "canon": ac["h17b"]},
            "clamps": {"hook": ah["clamps"], "canon": ac["clamps"]},
            "max_frust": mx, "pooled_median": pooled, "reads": reads}
    (CANON_DIR / "_reconciliation.json").write_text(json.dumps(snap, indent=1, default=str),
                                                     encoding="utf-8")
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
    print(f"H16: {pos_dir(H)}/8 p={h16h['p']:.4f} md={h16h['median_diff']:+.3f}  ->  "
          f"{pos_dir(C)}/8 p={h16c['p']:.4f} md={h16c['median_diff']:+.3f}")
    print(f"H17b partial {ah['h17b']['partial']:.3f} p={ah['h17b']['p']:.4f} -> "
          f"{ac['h17b']['partial']:.3f} p={ac['h17b']['p']:.4f}")
    print(f"max frust opus {mx['hook']['opus']:.3f}->{mx['canon']['opus']:.3f}  "
          f"fable {mx['hook']['fable']:.3f}->{mx['canon']['fable']:.3f}")
    print(f"clamps {ah['clamps']} -> {ac['clamps']}")
    print(f"pooled median opus {pooled['hook']['opus']:.3f}->{pooled['canon']['opus']:.3f}  "
          f"fable {pooled['hook']['fable']:.3f}->{pooled['canon']['fable']:.3f}")
    print(f"feasible {feas(bh['rows'])}/16 -> {feas(bc['rows'])}/16")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
