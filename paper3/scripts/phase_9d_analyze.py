"""Phase 9D — the held-out Opus 5.5 arm, scored as pre-registered.

Pre-registration: data/swebench_pilot/PREREGISTRATION_PHASE9D_OPUS55.md
(committed 17edf34, amendments e2136cc and c6904b6, all before the data they
govern). This script only applies the definitions frozen there. The monitor
functions are IMPORTED from scripts/budget_ceiling_9c.py rather than
reimplemented, so they are byte-identical to the ones that produced the 9C
results.

H19 and H20 are each scored twice (Amendment 2): on the hook count, exactly as
pre-registered, and on the transcript count, which governs interpretation
because the PostToolUse hook cannot see failed tool calls.

Run from repo root:  python scripts/phase_9d_analyze.py
"""
from __future__ import annotations

import json
import statistics
import subprocess
import sys
from pathlib import Path
from typing import Dict, List

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from budget_ceiling_9c import (fires_i1_wallclock, fires_i1_sampletime,   # noqa: E402
                               fires_i2, N_MIN_I1, N_MIN_I2, SHELL)
from hook_coverage_audit import transcript_calls, SUB                     # noqa: E402

C2 = ROOT / "data" / "live_runs" / "phase_c2"          # hook data: the "hook count" column
CANON = ROOT / "data" / "live_runs" / "phase_c2_canonical"   # canonical: cadence
OUT = ROOT / "data" / "swebench_pilot" / "PHASE_9D_REPORT.md"
SPECS = ["S02", "S03", "S05", "S06", "S07", "S08", "S09", "S10"]
R_GRID = [1, 2, 3, 4, 5, 10]


def sha() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True,
                              text=True, check=True).stdout.strip()[:12]
    except Exception:
        return "(unknown)"


def offset_rate(e: List[int], fn, r: int, gaps=None) -> float:
    """Fraction of sampling offsets on which the monitor fires (the frozen
    direct-subsampling procedure). For the wall-clock monitor the gap between
    two observed actions is the sum of the real gaps it skipped."""
    hits = 0
    for o in range(r):
        idx = list(range(o, len(e), r))
        sub = [e[i] for i in idx]
        if gaps is None:
            hits += bool(sub) and fn(sub)
        else:
            g = [sum(gaps[idx[j - 1]:idx[j]]) for j in range(1, len(idx))]
            hits += bool(sub) and fn(sub, g)
    return hits / r


def main() -> int:
    tmap: Dict[str, str] = json.loads((C2 / "_9d_transcript_map.json").read_text())
    runs = []
    for s in SPECS:
        run = json.loads((C2 / f"{s}_opus55_r1.json").read_text(encoding="utf-8"))
        crun = json.loads((CANON / f"{s}_opus55_r1.json").read_text(encoding="utf-8"))
        recs = [json.loads(l) for l in (C2 / s / "session_opus55_r1.jsonl")
                .read_text(encoding="utf-8").splitlines() if l.strip()]
        e_hook = [1 if (r["tool_name"] in SHELL and r["error_indicator"]) else 0 for r in recs]
        calls, models = transcript_calls(SUB / tmap[f"{s}_opus55"])
        e_true = [1 if (c["name"] in SHELL and c["err"]) else 0 for c in calls]
        runs.append({
            "spec": s, "models": sorted(models),
            "n_hook": len(recs), "n_true": len(calls),
            "E_hook": sum(e_hook), "E_true": sum(e_true),
            "e_hook": e_hook, "e_true": e_true, "dts": run["dt_seconds"],
            "median_dt": crun["dt_stats"]["median"],
            "tools": run["tools_used"], "git_recon": run["git_recon_calls"],
            "green": run["final_tests_green"],
        })

    assert all(r["models"] == ["claude-opus-5-5"] for r in runs), \
        "a transcript records a model other than claude-opus-5-5"

    def score(key_e: str, key_stream: str):
        feasible = sum(1 for r in runs if r[key_e] >= N_MIN_I1)
        i2 = sum(1 for r in runs if fires_i2(r[key_stream]))
        i1 = sum(1 for r in runs if fires_i1_sampletime(r[key_stream]))
        return feasible, i2, i1

    f_h, i2_h, i1_h = score("E_hook", "e_hook")
    f_t, i2_t, i1_t = score("E_true", "e_true")
    h19 = lambda f: "SUPPORTED" if f <= 2 else "FALSIFIED"
    h20 = lambda a, b: "SUPPORTED" if a > b else "FALSIFIED"

    O: List[str] = []
    w = O.append
    w("# Phase 9D — held-out Opus 5.5 arm")
    w("")
    w(f"Generated by `scripts/phase_9d_analyze.py` at `{sha()}`. Pre-registered "
      f"at `17edf34`; amendments `e2136cc` (launch prompts recovered verbatim "
      f"from the hook log) and `c6904b6` (hook blind to failed calls; scored "
      f"twice), each committed before the data it governs. 8 runs, one per "
      f"frozen 9C spec, clean-git protocol unchanged, **8/8 target suites "
      f"green, 8/8 transcripts record `claude-opus-5-5`**.")
    w("")
    w("This is **not a model comparison** and is **not pooled** with the frozen "
      "16 Phase-9C runs. It is a prospective test of the paper's one remaining "
      "empirical measurement, on a model released after that analysis was frozen.")
    w("")
    w("## Hypotheses")
    w("")
    w("| | pre-registered | hook count | **transcript count (governs)** |")
    w("|---|---|---|---|")
    w(f"| **H19** — floor binds | ≤ 2 of 8 sessions with E_X ≥ {N_MIN_I1} | "
      f"{f_h}/8 → {h19(f_h)} | **{f_t}/8 → {h19(f_t)}** |")
    w(f"| **H20** — design advice transfers | I2 fires on more sessions than I1 (no decay) at r = 1 | "
      f"I2 {i2_h} vs I1 {i1_h} → {h20(i2_h, i1_h)} | **I2 {i2_t} vs I1 {i1_t} → {h20(i2_t, i1_t)}** |")
    w("")
    agree19 = h19(f_h) == h19(f_t)
    agree20 = h20(i2_h, i1_h) == h20(i2_t, i1_t)
    w(f"The two instruments **{'agree' if agree19 else 'DISAGREE'}** on H19 and "
      f"**{'agree' if agree20 else 'DISAGREE'}** on H20.")
    w("")
    w("## Per session")
    w("")
    w("| spec | calls (transcript / hook) | E_X hook | **E_X true** | I1 fires | I2 fires | median Δt (s) | git recon | green |")
    w("|---|---|---|---|---|---|---|---|---|")
    for r in runs:
        w(f"| {r['spec']} | {r['n_true']} / {r['n_hook']} | {r['E_hook']} | **{r['E_true']}** | "
          f"{'Y' if fires_i1_sampletime(r['e_true']) else '·'} | "
          f"{'Y' if fires_i2(r['e_true']) else '·'} | {r['median_dt']} | "
          f"{r['git_recon']} | {'Y' if r['green'] else '**n**'} |")
    w("")
    nt = [r["n_true"] for r in runs]
    et = [r["E_true"] for r in runs]
    w(f"Session length (transcript): median **{statistics.median(nt):.1f}** "
      f"[{min(nt)}–{max(nt)}]. E_X (transcript): median **{statistics.median(et):.1f}** "
      f"[{min(et)}–{max(et)}]. Calls the hook missed: "
      f"**{sum(r['n_true'] - r['n_hook'] for r in runs)}**, every one a failed call.")
    w("")
    w("## Under a monitoring budget (transcript streams, averaged over offsets)")
    w("")
    w("| r | I1 no-decay | I2 CUSUM |")
    w("|---|---|---|")
    for rr in R_GRID:
        a = statistics.mean(offset_rate(r["e_true"], fires_i1_sampletime, rr) for r in runs)
        b = statistics.mean(offset_rate(r["e_true"], fires_i2, rr) for r in runs)
        w(f"| {rr} | {a:.0%} | {b:.0%} |")
    w("")
    w("## Reading")
    w("")
    w(f"- **H19 is {h19(f_t)} under both instruments.** No Opus 5.5 session "
      f"carries the {N_MIN_I1} qualifying observations the reference "
      f"accumulator needs; the largest count is {max(et)}. **Held out on "
      f"model, not on task:** these are the same eight tasks, and session "
      f"length is set mostly by the task. So H19 shows the floor survives a "
      f"model generation on these tasks. It does not show that agent "
      f"sessions in general are short — which fits the paper's claim that "
      f"the task distribution, not the model, decides feasibility.")
    if h20(i2_t, i1_t) == "FALSIFIED":
        w(f"- **H20 is FALSIFIED.** With at most {max(et)} failed command(s) per "
          f"session, the 2-event CUSUM fires on {i2_t} session(s), no more than "
          f"the 5-event accumulator. **The paper's design advice — lower the "
          f"floor — recovers nothing on this model**, because its sessions "
          f"carry almost no failures to accumulate. This must be stated in "
          f"§3.6 and §5.2: a smaller N_min helps only when the evidence exists.")
    else:
        r2 = statistics.mean(offset_rate(r["e_true"], fires_i2, 2) for r in runs)
        w(f"- **H20 is SUPPORTED under its clause, and carries no "
          f"information.** The 2-event CUSUM fires on {i2_t} session(s) against "
          f"{i1_t} — the narrowest margin the clause allows — and that session "
          f"does not survive halving the budget (I2 at r = 2: {r2:.0%}). "
          f"**Do not cite H20 for the CUSUM recommendation.** The evidence for "
          f"it is Phase 9C on the corrected count: 8 of 16 sessions against 1.")
    w("- **No comparison with Opus 5 or Fable 5.1 is claimed**, as pre-registered: "
      "n = 8 cannot separate models (9C's H16: p = 0.38 on the corrected "
      "count, 0.84 as originally scored), and effort was not "
      "matched. The per-session numbers are descriptive.")
    w("- **Instrument.** Opus 5.5 lets failing pytest runs exit non-zero, as "
      "Fable 5.1 did and Opus 5 did not, so the hook undercounts it. That the "
      "hook-based and transcript-based verdicts agree here is because every "
      "session sits far below the floor, not because the hook is sound.")
    w("- **Model identity is taken from the record, not the alias.** The Agent "
      "tool's `opus` alias meant Opus 5 when 9C ran and Opus 5.5 when 9D ran; "
      "with the default run label, 9D would have overwritten the frozen Opus 5 "
      "files. Aliases drift, so the resolved model ID in each subagent "
      "transcript (`claude-opus-5-5` here, `claude-opus-5` and "
      "`claude-fable-5-1` in 9C) is the record, and future runs carry the "
      "full ID in their filenames.")
    w("")

    OUT.write_text("\n".join(O), encoding="utf-8")
    (C2 / "_phase_9d.json").write_text(json.dumps(
        {"runs": [{k: v for k, v in r.items() if k not in ("e_hook", "e_true", "dts")} for r in runs],
         "H19": {"hook": [f_h, h19(f_h)], "transcript": [f_t, h19(f_t)]},
         "H20": {"hook": [i2_h, i1_h, h20(i2_h, i1_h)],
                 "transcript": [i2_t, i1_t, h20(i2_t, i1_t)]}}, indent=1),
        encoding="utf-8")
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
    print(f"H19: hook {f_h}/8 {h19(f_h)} | transcript {f_t}/8 {h19(f_t)}")
    print(f"H20: hook I2 {i2_h} vs I1 {i1_h} {h20(i2_h, i1_h)} | "
          f"transcript I2 {i2_t} vs I1 {i1_t} {h20(i2_t, i1_t)}")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
